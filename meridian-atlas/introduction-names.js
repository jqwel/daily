let introductionNameIndex;
function buildIntroductionNameIndex() {
  const candidates = new Map();
  const entryNames = new Map(window.PLACES.map((place) => [place.id, place.name]));
  const { names, places, landmarks, pins } = window.EDITION;
  function add(zh, en, ipa, owner) {
    const name = zh?.split(/[（(]/, 1)[0].trim();
    if (!name || name.length < 2 || !/\p{Script=Han}/u.test(name) ||
        !en || !ipa?.startsWith("/") || !ipa.endsWith("/")) return;
    if (!candidates.has(name)) candidates.set(name, new Map());
    const variants = candidates.get(name);
    const key = en.toLowerCase();
    if (!variants.has(key)) variants.set(key, { en, ipa, owners: new Set() });
    if (owner) variants.get(key).owners.add(owner);
  }
  for (const place of window.PLACES) {
    const local = names[place.id];
    add(local?.zh, place.name, place.ipa, place.id);
    for (const alias of local?.aliasesZh || []) add(alias, place.name, place.ipa, place.id);
    const english = place.capital?.split(" · ") || [];
    const readings = place.capitalIpa?.split(" · ") || [];
    const chinese = local?.capitalZh?.split(/\s*[·／]\s*/) || [];
    if (english.length === chinese.length)
      english.forEach((en, i) => add(chinese[i], en, readings[i], place.id));
  }
  for (const place of places) {
    if (!place.capitalReading) continue;
    const [ipa, zh] = place.capitalReading;
    add(zh, place.capital, ipa, place.id);
  }
  for (const pin of pins) {
    const name = landmarks[pin.key];
    if (name) add(name.zh, pin.target, name.ipa, pin.placeId);
  }
  for (const [owner, groups] of Object.entries(LOOKUP_SUPPLEMENTS)) {
    for (const rows of Object.values(groups)) {
      for (const [en, zh, url, ...aliases] of rows) {
        const reading = SUPPLEMENT_MEDIA[url]?.ipa;
        add(zh, en, reading, owner);
        for (const alias of aliases) add(alias, en, reading, owner);
      }
    }
  }
  for (const [aliases, en, ipa] of INTRODUCTION_NAMES) {
    for (const name of aliases.split(" "))
      candidates.set(name, new Map([[en.toLowerCase(), { en, ipa, owners: new Set() }]]));
  }
  // Keep common geographic phrases intact when part of the phrase is also a name.
  const ordinaryPhrases = ["北海岸", "沿海地区", "沿海地带", "临海地区", "近海地区"];
  const alternatives = [...ordinaryPhrases, ...candidates.keys()].sort((a, b) => b.length - a.length)
    .map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  // A nickname or title in quotes is one unit, even if only part of it is known.
  const quoted = "“[^”\n]+”|「[^」\n]+」|《[^》\n]+》";
  const pattern = new RegExp("(" + quoted + "|" + alternatives.join("|") + ")([（(][^（）()\n]*[）)])?", "gu");
  return { candidates, entryNames, pattern };
}

function introductionNameKey(name) {
  return name.trim().toLowerCase().replaceAll("’", "'");
}

function atlasIntroduction(text, owner, subject) {
  if (!text) return text;
  introductionNameIndex ??= buildIntroductionNameIndex();
  const { candidates, entryNames, pattern } = introductionNameIndex;
  const scope = owner?.startsWith("US-") ? "USA" : owner;
  const omitted = new Set([entryNames.get(owner), entryNames.get(scope), subject]
    .filter(Boolean).flatMap((name) => name.split(" · ").map(introductionNameKey)));
  const seen = new Set();
  return text.replace(pattern, (match, displayName, qualifier = "", offset) => {
    const name = displayName.replace(/^[“「《]|[”」》]$/g, "");
    if (!candidates.has(name)) return match;
    const variants = [...candidates.get(name).values()];
    const local = variants.filter((entry) => entry.owners.has(owner));
    const reading = local.length === 1 ? local[0] : variants.length === 1 ? variants[0] : null;
    if (!reading) return match;
    const { en, ipa } = reading;
    const key = introductionNameKey(en);
    const current = qualifier.slice(1, -1).trim();
    const qualifierName = introductionNameKey(current.replace(/\s+\/[^/]+\/$/, ""));
    if (omitted.has(key)) return qualifierName === key ? displayName : match;
    if (seen.has(key)) return match;
    seen.add(key);
    if (/\p{Script=Latin}/u.test(current)) {
      if (introductionNameKey(current) === key) return displayName + "（" + en + " " + ipa + "）";
      return match;
    }
    const definition = text.slice(0, offset)
      .match(/(\p{Script=Latin}[\p{Script=Latin}\p{M}'’ -]*)\s*(?:是|指|意为|表示)\s*$/u)?.[1];
    if (definition && introductionNameKey(definition) === key) return displayName + "（" + ipa + "）" + qualifier;
    return displayName + "（" + en + " " + ipa + "）" + qualifier;
  });
}
