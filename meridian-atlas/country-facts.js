function atlasCountryFacts(id) {
  const fields = [];
  const language = atlasLanguageFacts.get(id);
  if (language) fields.push(language);
  const [adjective, singular, plural] = atlasCountryForms[id] || [];
  if (adjective)
    fields.push(["Country adjective · 国家形容词", countryFormReadout([[adjective]])]);
  if (singular) {
    const forms = [];
    if (!plural) forms.push([singular]);
    else if (singular === plural) forms.push([singular, "单复数同形"]);
    else forms.push([singular, "单数"], [plural, "复数"]);
    fields.push(["Demonym · 国民称谓", countryFormReadout(forms)]);
  }
  return fields;
}

function countryFormReadout(forms) {
  const list = element("span", "country-form-list");
  for (const [variants, number] of forms) {
    for (const variant of variants.split(" / ")) {
      const [name, note] = variant.split("（");
      const reading = name.toLowerCase().split(" ").map((word) => atlasCountryPronunciations[word]).join(" ");
      const line = element("span", "country-form");
      line.append(element("span", "", name), " ", element("span", "ipa", "/" + reading + "/"));
      const label = [note?.slice(0, -1), number].filter(Boolean).join(" · ");
      if (label) {
        const detail = element("small", "word-zh", label);
        detail.lang = "zh-Hans";
        line.append(" ", detail);
      }
      list.append(line);
    }
  }
  return list;
}
